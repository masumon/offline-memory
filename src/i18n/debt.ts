/** Human label for a stored purpose key; unknown keys (a user's own) pass through. */
export function purposeLabel(key: string | null | undefined, language: AppLanguage): string {
  if (!key) return '';
  const map: Record<string, [string, string]> = {
    EMERGENCY: ['জরুরি', 'Emergency'], FAMILY: ['পরিবার', 'Family'], EDUCATION: ['শিক্ষা', 'Education'],
    MEDICAL: ['চিকিৎসা', 'Medical'], HOUSE: ['বাড়ি', 'House'], VEHICLE: ['যানবাহন', 'Vehicle'],
    PERSONAL: ['ব্যক্তিগত', 'Personal'], BUSINESS: ['ব্যবসা', 'Business'], OLD_DEBT: ['পুরনো ঋণ', 'Old debt'],
    DAILY_EXPENSE: ['দৈনন্দিন', 'Daily expense'], OTHER: ['অন্যান্য', 'Other'],
  };
  const entry = map[key];
  return entry ? (language === 'bn' ? entry[0] : entry[1]) : key;
}
